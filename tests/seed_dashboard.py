    async def responses_session(self, sid: str, hours_ago: float, workspace: str, opening: str,
                                turns: list[dict[str, Any]]) -> None:
        self.start(hours_ago, {"task": "code-edit", "difficulty": 1.2, "harm": 0.2})
        self.made.append(sid)
        caller = H.ResponsesClient(self.svc, session_id=sid, alias="astra-adaptive", client="codex",
                                   token=admin_token())
        env = H.user_item(f"<environment_context>\n  <cwd>/Users/dev/src/{workspace}</cwd>\n"
                          "  <shell>zsh</shell>\n</environment_context>")
        response = await self.svc.client.post("/router/resolve", headers=caller.control_headers(), json={
            "schema_version": "1", "intent": "new", "session_id": sid, "request_id": "resolve-0001",
            "alias": caller.alias, "client": caller.client,
            "client_contract": {"dynamic_metadata": True, "protocols": ["openai-responses"],
                                "fresh_execution_context": True, "turn_boundary_reporting": True},
            "request": {"instructions": "You are Codex, a coding agent.",
                        "input": [env, H.user_item(opening)], "max_output_tokens": 4096},
            "limits": {"max_output_tokens": 4096},
        })
        if response.status_code != 200:
            raise RuntimeError(f"resolve failed: {response.text}")
        caller.binding = response.json()["binding_revision"]
        caller.execution = response.json()["execution"]
        caller.items = [env, H.user_item(opening)]
        await self.responses_turn(caller, turns[0]["steps"], turns[0]["answer"], plan=None)
        for turn in turns[1:]:
            self.pause()
            self.script.turn = turn["jev"]
            plan = await caller.plan(turn["prompt"], task=opening)
            if plan["_status"] != 200:
                raise RuntimeError(f"turn plan failed: {plan}")
            caller.record(plan, turn["prompt"])
            await self.responses_turn(caller, turn["steps"], turn["answer"], plan=plan)

    async def responses_turn(self, caller: Any, steps: list[tuple[str, dict[str, Any]]],
                             answer: str, plan: dict[str, Any] | None) -> None:
        for n, step in enumerate([*steps, None]):
            self.script.reply = {"call": step} if step else {"text": answer}
            self.script.clock.advance(self.script.rng.uniform(0.3, 2.0))
            sent = await caller.send(plan if n == 0 else None,
                                     turn_id="" if plan is None else plan["turn_id"])
            if sent.status_code != 200:
                raise RuntimeError(f"responses execution failed: {sent.status_code} {sent.text}")
            if step:
                self.script.clock.advance(self.script.rng.uniform(2.0, 15.0))
                call_id = next(item["call_id"] for item in reversed(caller.items)
                               if item.get("type") == "function_call")
                caller.items.append({"type": "function_call_output", "call_id": call_id,
                                     "output": tool_output(step[0])})
        self.script.reply = {}

