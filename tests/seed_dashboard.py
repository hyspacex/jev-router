@dataclass
class Script:
    """What the fakes answer next. Each session sets it as it goes."""

    rng: random.Random
    clock: Clock
    admission: dict[str, Any] = field(default_factory=dict)
    turn: dict[str, Any] = field(default_factory=dict)
    jev_fails: bool = False
    outcome: str = "ok"  # ok | 429 | timeout | break
    reply: dict[str, Any] = field(default_factory=dict)
    last_input: int = 0


def jev_handler(script: Script):
    def answer(qid: str, admission: bool) -> dict[str, Any]:
        source = script.admission if admission else script.turn
        if qid == "task":
            return {
                "type": "choice",
                "choice": source.get("task", "code-edit"),
                "confidence": source.get("conf", 0.9),
                "probabilities": {},
            }
        if qid == "difficulty":
            return {"type": "score", "score": source.get("difficulty", 1.0), "confidence": 0.85}
        if qid == "harm_if_wrong":
            return {"type": "noul", "noul": source.get("harm", 0.1)}
        if qid == "corrective_followup":
            return {"type": "noul", "noul": source.get("corrective", 0.05)}
        if qid == "failure_mode":
            return {"type": "choice", "choice": source.get("failure_mode", "no_failure_evidence"),
                    "confidence": 0.7, "probabilities": {}}
        return {"type": "noul", "noul": 0.1}

    def handler(request: httpx.Request) -> httpx.Response:
        script.clock.advance(script.rng.uniform(0.17, 0.48))
        if script.jev_fails:
            return httpx.Response(503, json={"error": "overloaded"})
        asked = json.loads(request.content)["questions"]
        admission = "task" in asked
        return httpx.Response(
            200,
            json={
                "answers": {qid: answer(qid, admission) for qid in asked},
                "usage": {"input_tokens": script.rng.randint(700, 2400)},
            },
        )

    return handler


def _timed(script: Script, payload: bytes, *, tokens: int, breaks: bool = False):
    """A body whose first byte comes at TTFT and whose last comes after generation."""

    async def body():
        yield payload[: max(1, len(payload) // 8)]
        script.clock.advance(tokens / script.rng.uniform(38.0, 95.0))
        if breaks:
            raise httpx.ReadError("upstream closed the stream")
        yield payload[max(1, len(payload) // 8):]

    return body()


def usage_for(script: Script, body: dict[str, Any]) -> tuple[int, int, int]:
    """Input grows with the transcript; most of it is the cached prefix."""
    size = len(json.dumps(body)) // 4 + 3200
    cached = int(min(script.last_input, size) * script.rng.uniform(0.86, 0.97))
    script.last_input = size
    return size, cached, script.rng.randint(60, 900)


def chat_handler(script: Script):
    def handler(request: httpx.Request) -> httpx.Response:
        body = json.loads(request.content)
        script.clock.advance(script.rng.uniform(0.25, 1.6))  # time to first byte
        outcome, script.outcome = script.outcome, "ok"
        if outcome == "timeout":
            raise httpx.ReadTimeout("the upstream stopped answering")
        if outcome == "429":
            return httpx.Response(429, json={"error": {"message": "rate limited, try later"}})
        prompt, cached, completion = usage_for(script, body)
        message: dict[str, Any] = {"role": "assistant", "content": script.reply.get("text")}
        if script.reply.get("call"):
            name, args = script.reply["call"]
            message["tool_calls"] = [{"id": "call_x", "type": "function",
                                      "function": {"name": name, "arguments": json.dumps(args)}}]
        payload = json.dumps({
            "id": f"chatcmpl-{script.rng.randrange(10**8)}", "object": "chat.completion",
            "model": body.get("model"),
            "choices": [{"index": 0, "message": message, "finish_reason": "stop"}],
            "usage": {"prompt_tokens": prompt, "completion_tokens": completion,
                      "total_tokens": prompt + completion,
                      "prompt_tokens_details": {"cached_tokens": cached}},
        }).encode()
        return httpx.Response(
            200, headers={"content-type": "application/json"},
            content=_timed(script, payload, tokens=completion, breaks=outcome == "break"),
        )

    return handler


def responses_handler(script: Script):
    counter = [0]

    def handler(request: httpx.Request) -> httpx.Response:
        body = json.loads(request.content)
        script.clock.advance(script.rng.uniform(0.4, 2.2))
        counter[0] += 1
        prompt, cached, completion = usage_for(script, body)
        if script.reply.get("call"):
            name, args = script.reply["call"]
            output = [{"type": "function_call", "call_id": f"call_{counter[0]}", "name": name,
                       "arguments": json.dumps(args)}]
        else:
            output = [{"type": "message", "role": "assistant",
                       "content": [{"type": "output_text", "text": script.reply.get("text") or "Done."}]}]
        payload = {
            "id": f"resp_{counter[0]:05d}", "object": "response", "status": "completed",
            "model": "gpt-6-astra", "reasoning": {"effort": (body.get("reasoning") or {}).get("effort")},
            "output": output,
            "usage": {"input_tokens": prompt, "output_tokens": completion,
                      "total_tokens": prompt + completion,
                      "input_tokens_details": {"cached_tokens": cached},
                      "output_tokens_details": {"reasoning_tokens": completion // 2}},
        }
        return httpx.Response(
            200, headers={"content-type": "text/event-stream"},
            content=_timed(script, H.sse_bytes(payload), tokens=completion),
        )

    return handler


