# --- the clock the app reads -------------------------------------------------


class Clock:
    """Wall time and perf time, moved together and only by this script."""

    def __init__(self, start: float) -> None:
        self.wall = start
        self.perf = 1000.0

    def time(self) -> float:
        return self.wall

    def perf_counter(self) -> float:
        return self.perf

    def advance(self, seconds: float) -> None:
        self.wall += seconds
        self.perf += seconds


class FakeTime:
    """The `time` module, except for the two readings the app logs."""

    def __init__(self, clock: Clock) -> None:
        self._clock = clock

    def time(self) -> float:
        return self._clock.time()

    def perf_counter(self) -> float:
        return self._clock.perf_counter()

    def __getattr__(self, name: str) -> Any:
        return getattr(real_time, name)


