def adaptive_overlay() -> tuple[Any, Any, str]:
    path = REPO / "examples" / "make-adaptive-astra.py"
    spec = importlib.util.spec_from_file_location("make_adaptive_astra", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module.overlay, module.merge, str(module.REPORT)


def write_config(db: Path, out: Path) -> None:
    overlay, merge, report = adaptive_overlay()
    raw = yaml.safe_load((REPO / "router.yaml").read_text())
    raw = merge(raw, overlay(report))
    settings = raw["settings"]
    settings.update(
        {
            "sqlite_path": str(db),
            "mode": "active",
            "upstream_base_url": UPSTREAM,
            "jev_url": JEV_URL,
            "log_state": True,
            "scrub_secrets": True,
            "port": 18319,
        }
    )
    for provider in (raw.get("providers") or {}).values():
        quota = provider.get("quota")
        if isinstance(quota, dict):
            quota["enabled"] = False
    header = (
        "# A dashboard seed config, generated by tests/seed_dashboard.py from\n"
        "# router.yaml and examples/make-adaptive-astra.py. Its upstream and Jev\n"
        "# URLs cannot resolve: it is for looking at the seeded database only.\n"
    )
    out.write_text(header + yaml.safe_dump(raw, sort_keys=False, width=100))


