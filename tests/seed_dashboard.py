@dataclass
class Turn:
    prompt: str
    steps: list[tuple[str, dict[str, Any]]]
    answer: str


class ChatSession:
    """A Pi-like client: it keeps the transcript and sends the whole thing."""

    def __init__(self, svc: Any, script: Script, session_id: str, workspace: str | None,
                 *, tools: bool = True) -> None:
        self.script = script
        self.caller = H.Client(svc, session_id=session_id, client="pi", alias="auto", token=admin_token())
        self.messages: list[dict[str, Any]] = []
        if workspace:
            self.messages.append({"role": "system", "content": pi_system(workspace)})
        self.tools = tools

    def body(self, model: str = "") -> dict[str, Any]:
        out: dict[str, Any] = {"messages": json.loads(json.dumps(self.messages)), "max_tokens": 2048}
        if self.tools:
            out["tools"] = TOOLS
        if model:
            out["model"] = model
        return out

    async def admit(self, content: Any) -> dict[str, Any]:
        self.messages.append({"role": "user", "content": content})
        response = await self.caller.resolve(request=self.body())
        if response.status_code != 200:
            raise RuntimeError(f"resolve failed: {response.status_code} {response.text}")
        return response.json()

    async def send(self, *, outcome: str = "ok", request_id: str | None = None) -> int:
        self.script.outcome = outcome
        self.script.clock.advance(self.script.rng.uniform(0.3, 2.5))
        try:
            response = await self.caller.execute(self.body(self.caller.wire_model()), request_id=request_id)
        except httpx.HTTPError:
            return 599  # the stream broke after the headers
        return response.status_code

    async def run_turn(self, turn: Turn, *, first: bool, finish: bool = True) -> None:
        if not first:
            self.messages.append({"role": "user", "content": turn.prompt})
        await self.send()
        for n, (name, args) in enumerate(turn.steps):
            self.script.clock.advance(self.script.rng.uniform(2.0, 18.0))  # the tool runs
            cid = f"call_{len(self.messages)}_{n}"
            self.messages.append({"role": "assistant", "content": None, "tool_calls": [
                {"id": cid, "type": "function", "function": {"name": name, "arguments": json.dumps(args)}}]})
            self.messages.append({"role": "tool", "tool_call_id": cid, "content": tool_output(name)})
            await self.send()
        if finish:
            self.messages.append({"role": "assistant", "content": turn.answer})

    async def feedback(self, verdict: str, note: str | None = None, adjust: bool = True) -> dict[str, Any]:
        body: dict[str, Any] = {"verdict": verdict, "adjust_effort": adjust, "source": "pi",
                                "request_id": f"execution-{self.caller.counter:04d}"}
        if note:
            body["note"] = note
        response = await self.caller.service.client.post(
            f"/router/sessions/{self.caller.session_id}/feedback", json=body,
            headers=self.caller.control_headers())
        result = response.json()
        if result.get("effort_changed"):
            self.caller.execution["wire_model"] = result["wire_model"]
        return result


def tool_output(name: str) -> str:
    return {
        "read_file": "def retry(fn, attempts=3):\n    ...\n",
        "edit_file": "Applied 1 edit.",
        "bash": "....F.\n1 failed, 5 passed in 2.31s",
        "grep": "billing/retry.py:42: delay = random.uniform(0, cap)",
    }.get(name, "ok")


def loop(*steps: tuple[str, dict[str, Any]], repeat: int = 1) -> list[tuple[str, dict[str, Any]]]:
    return [step for _ in range(repeat) for step in steps]


