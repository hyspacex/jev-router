async def seed(db: Path, config_path: Path, rng_seed: int) -> list[tuple[str, str | None]]:
    os.environ.pop(UPSTREAM_ENV, None)
    os.environ.setdefault("TYPESAFE_API_KEY", "seed-not-a-real-key")
    os.environ.setdefault("JEV_ROUTER_ADMIN_TOKEN", "seed-admin-token")
    config = load_config(config_path)

    now = real_time.time()
    clock = Clock(now - HOURS * 3600)
    fake = FakeTime(clock)
    for module in (app_module, pins_module, sessions_module, jev_module):
        module.time = fake  # the app's readings only; nothing else moves

    script = Script(rng=random.Random(rng_seed), clock=clock)
    store = pins_module.Store(db, log_state=True, text_max_chars=config.settings.turn_text_max_chars)
    app = app_module.create_app(config, store)

    class Svc:
        pass

    svc = Svc()
    svc.app = app
    svc.router = app.state.router
    svc.sessions = app.state.router.sessions
    svc.store = store
    svc.config = config
    svc.client = httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://router.seed")

    seeder = Seeder(svc, script, now)
    try:
        with respx.mock(assert_all_called=False) as mock:
            mock.post(JEV_URL).mock(side_effect=jev_handler(script))
            mock.post(CHAT).mock(side_effect=chat_handler(script))
            mock.post(RESPONSES).mock(side_effect=responses_handler(script))
            for step in (
                seeder.easy_question, seeder.flaky_retry, seeder.stack_trace, seeder.image,
                seeder.low_confidence, seeder.fallback, seeder.stream_failure, seeder.rejected,
                seeder.outcome_unknown, seeder.leaked_key, seeder.too_strong, seeder.closed,
                seeder.blocked, seeder.design_review, seeder.adaptive_escalation,
                seeder.adaptive_downgrade, seeder.adaptive_steady,
            ):
                await step()
        return [(sid, (svc.sessions.get(sid) or {}).get("title")) for sid in seeder.made]
    finally:
        await svc.client.aclose()
        await svc.router.aclose()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", required=True, help="the router.db to create")
    parser.add_argument("--config", required=True, help="where to write the config to serve it with")
    parser.add_argument("--seed", type=int, default=7, help="the random seed for timings and usage")
    parser.add_argument("--force", action="store_true", help="replace an existing database")
    args = parser.parse_args(argv)

    db = Path(args.db).expanduser().resolve()
    config_path = Path(args.config).expanduser().resolve()
    if db.exists():
        if not args.force:
            print(f"{db} exists; pass --force to replace it", file=sys.stderr)
            return 2
        for suffix in ("", "-wal", "-shm"):
            Path(f"{db}{suffix}").unlink(missing_ok=True)
    db.parent.mkdir(parents=True, exist_ok=True)
    config_path.parent.mkdir(parents=True, exist_ok=True)
    write_config(db, config_path)

    # The fakes produce a 429, a timeout, a broken stream and a Jev outage on
    # purpose; their warnings are expected and would only be noise here.
    logging.disable(logging.CRITICAL)
    made = asyncio.run(seed(db, config_path, args.seed))
    logging.disable(logging.NOTSET)

    print(f"database: {db}")
    print(f"config:   {config_path}")
    for sid, title in made:
        print(f"  {sid:34} {title or '-'}")
    print(f"\nserve it:  JEV_ROUTER_ADMIN_TOKEN=... uv run jev-router -c {config_path} serve")
    return 0


